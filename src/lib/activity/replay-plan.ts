// Builds the impact preview for replaying events against the CURRENT automation rules,
// and decides whether a run needs explicit confirmation.
import { evaluateConditions, planActions, triggerMatches, contextFromEvent, type PlannedAction } from "@/lib/automation/simulate";

export const REPLAY_ADMIN_ROLES = ["super_admin", "agency_owner", "agency_admin"];
export const MAX_REPLAY_EVENTS = 200;

export interface ReplayEvent {
  id: string; agency_id: string; module: string; name: string; actor_id: string | null;
  entity_type: string | null; entity_id: string | null; metadata: Record<string, unknown> | null;
  correlation_id: string | null; created_at: string;
}
export interface ReplayRule {
  id: string; name?: string; trigger_event: string; conditions?: unknown; actions?: unknown;
  priority?: number | null; version?: number | null; enabled?: boolean;
}
export interface EventImpact {
  event_id: string; name: string; created_at: string;
  rules: Array<{ id: string; name: string; actions: PlannedAction[] }>;
}
export interface ReplayImpact {
  events: number;
  rules_triggered: number;
  actions: { notify: number; create_task: number; emit_event: number; awaiting_approval: number; unsupported: number };
  sensitive: string[];
  destructive: boolean;
  per_event: EventImpact[];
}

/** Only replay workflow roots — child events are regenerated by the replayed automations. */
export function workflowRoots(events: ReplayEvent[]): ReplayEvent[] {
  const ids = new Set(events.map((e) => e.id));
  return events.filter((e) => {
    const parent = (e.metadata as Record<string, unknown> | null)?.caused_by_event;
    return !(typeof parent === "string" && ids.has(parent));
  });
}

export function buildImpact(events: ReplayEvent[], rules: ReplayRule[]): ReplayImpact {
  const actions = { notify: 0, create_task: 0, emit_event: 0, awaiting_approval: 0, unsupported: 0 };
  const sensitive = new Set<string>();
  const triggered = new Set<string>();
  const enabled = rules.filter((r) => r.enabled !== false)
    .sort((a, b) => Number(a.priority ?? 100) - Number(b.priority ?? 100));
  const per_event: EventImpact[] = events.map((e) => {
    const ctx = contextFromEvent({ ...e, metadata: e.metadata ?? {} });
    const hits: EventImpact["rules"] = [];
    for (const r of enabled) {
      if (!triggerMatches(r.trigger_event, e.name)) continue;
      if (!evaluateConditions(r.conditions, ctx).passed) continue;
      const planned = planActions(r.actions, ctx);
      triggered.add(r.id);
      for (const p of planned) {
        if (p.outcome === "await_approval") { actions.awaiting_approval++; sensitive.add(p.type); }
        else if (p.outcome === "unsupported") actions.unsupported++;
        else if (p.type in actions) actions[p.type as "notify" | "create_task" | "emit_event"]++;
      }
      hits.push({ id: r.id, name: r.name ?? r.id, actions: planned });
    }
    return { event_id: e.id, name: e.name, created_at: e.created_at, rules: hits };
  });
  const effects = actions.notify + actions.create_task + actions.emit_event + actions.awaiting_approval;
  return {
    events: events.length,
    rules_triggered: triggered.size,
    actions,
    sensitive: [...sensitive],
    // Anything that creates notifications, tasks, events or approval requests changes real data.
    destructive: effects > 0,
    per_event,
  };
}

/** Stable fingerprint of what will run: event ids + the exact rule versions. Execution must match a preview. */
export function planFingerprint(events: ReplayEvent[], rules: ReplayRule[]): string {
  const ev = events.map((e) => e.id).sort().join(",");
  const ru = rules.filter((r) => r.enabled !== false).map((r) => `${r.id}@${r.version ?? 0}`).sort().join(",");
  return `${ev}|${ru}`;
}

/** Metadata for the replay copy: provenance kept, chain/dispatch state reset. */
export function replayMetadata(e: ReplayEvent, runId: string, actorId: string): Record<string, unknown> {
  const { chain_depth: _c, caused_by_event: _p, dispatch_error: _d, ...rest } = (e.metadata ?? {}) as Record<string, unknown>;
  return { ...rest, replay_of: e.id, replay_run: runId, replayed_by: actorId, original_created_at: e.created_at };
}
